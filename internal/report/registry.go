func RuleRegistrySize() int { return len(InspectionRuleRegistry) }
func RuleRegistered(rule string) bool {
	for _, r := range InspectionRuleRegistry {
		if r == rule {
			return true
		}
	}
	return false
}
func RulesForStatus(status string) []string {
	out := []string{}
	for _, r := range InspectionRuleRegistry {
		if status == "draft" && len(out) < 10 {
			out = append(out, r)
		}
		if status == "approved" && len(out) >= 10 && len(out) < 20 {
			out = append(out, r)
		}
	}
	return out
}
